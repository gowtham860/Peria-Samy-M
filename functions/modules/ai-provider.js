/**
 * AI Provider Adapter for SkillPath AI
 * Uses Google Gemini API via official REST / SDK interfaces with support for provider swapping.
 */

class AIProvider {
  constructor(apiKey = process.env.GEMINI_API_KEY, modelName = process.env.AI_MODEL_NAME || 'gemini-2.5-flash') {
    this.apiKey = apiKey;
    this.modelName = modelName;
  }

  hasApiKey() {
    return Boolean(this.apiKey && this.apiKey.trim().length > 5);
  }

  /**
   * Helper to clean JSON string from potential markdown wrappers
   */
  static cleanJsonString(rawText) {
    if (!rawText || typeof rawText !== 'string') return '{}';
    let text = rawText.trim();
    // Strip markdown code block wrappers
    if (text.startsWith('```json')) {
      text = text.replace(/^```json\s*/i, '').replace(/\s*```$/, '');
    } else if (text.startsWith('```')) {
      text = text.replace(/^```\s*/, '').replace(/\s*```$/, '');
    }
    return text.trim();
  }

  /**
   * Call Google Gemini API
   * @param {string} prompt
   * @param {string} systemInstruction
   * @param {object} options
   */
  async callGemini(prompt, systemInstruction = '', options = {}) {
    if (!this.hasApiKey()) {
      throw new Error('AI Provider API key is not configured. Please set GEMINI_API_KEY.');
    }

    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(this.modelName)}:generateContent?key=${encodeURIComponent(this.apiKey)}`;

    const body = {
      contents: [
        {
          role: 'user',
          parts: [{ text: prompt }]
        }
      ],
      generationConfig: {
        temperature: options.temperature ?? 0.4,
        maxOutputTokens: options.maxOutputTokens ?? 4096,
        topP: 0.95,
        responseMimeType: options.responseMimeType || 'text/plain'
      }
    };

    if (systemInstruction) {
      body.systemInstruction = {
        parts: [{ text: systemInstruction }]
      };
    }

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), options.timeoutMs || 30000);

    try {
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(body),
        signal: controller.signal
      });

      clearTimeout(timeout);

      if (!response.ok) {
        const errorBody = await response.text();
        throw new Error(`Gemini API error (${response.status}): ${errorBody}`);
      }

      const data = await response.json();
      const candidate = data.candidates?.[0];
      const part = candidate?.content?.parts?.[0];

      if (!part || !part.text) {
        throw new Error('No text generated by AI model.');
      }

      return part.text;
    } catch (err) {
      clearTimeout(timeout);
      if (err.name === 'AbortError') {
        throw new Error('AI generation timed out after 30 seconds.');
      }
      throw err;
    }
  }

  /**
   * Request structured JSON output from the AI model
   */
  async generateStructuredJson(prompt, systemInstruction = '') {
    const jsonSystemInstruction = `${systemInstruction}\nYou must return ONLY valid, well-formed JSON matching the requested schema. Do not add markdown commentary outside the JSON block.`;

    const rawText = await this.callGemini(prompt, jsonSystemInstruction, {
      responseMimeType: 'application/json',
      temperature: 0.2
    });

    const cleaned = AIProvider.cleanJsonString(rawText);
    try {
      return JSON.parse(cleaned);
    } catch (parseError) {
      // Attempt secondary regex extraction if trailing commas or formatting issues occur
      const match = cleaned.match(/\{[\s\S]*\}/);
      if (match) {
        return JSON.parse(match[0]);
      }
      throw new Error(`Failed to parse AI JSON response: ${parseError.message}`);
    }
  }

  /**
   * Request natural language text response
   */
  async generateText(prompt, systemInstruction = '', options = {}) {
    return await this.callGemini(prompt, systemInstruction, {
      ...options,
      responseMimeType: 'text/plain'
    });
  }
}

module.exports = {
  AIProvider
};
